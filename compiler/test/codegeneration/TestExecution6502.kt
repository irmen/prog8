    test("div_longs positive 1234567890 / 88888 = 13889") {
        val src = $$"""
            %option no_sysinit
            %launcher none
            %address $1000
            
            main {
                &ubyte poweroff = $f203
                sub start() {
                    long @shared v = 1234567890
                    v /= 88888
                    %asm {{
                        lda p8v_v
                        sta $2000
                        lda p8v_v+1
                        sta $2001
                        lda p8v_v+2
                        sta $2002
                        lda p8v_v+3
                        sta $2003
                    }}
                    poweroff = 1
                }
            }
        """.trimIndent()
        val compileResult = compileText(Cx16Target(), false, src, outputDir)
        val machine = compileResult!!.simulate(maxCycles = 30000)
        val b0 = machine.ram[0x2000].toInt() and 0xff
        val b1 = machine.ram[0x2001].toInt() and 0xff
        val b2 = machine.ram[0x2002].toInt() and 0xff
        val b3 = machine.ram[0x2003].toInt() and 0xff
        println("div_longs result bytes: $b0 $b1 $b2 $b3 (hex: ${b0.toString(16)} ${b1.toString(16)} ${b2.toString(16)} ${b3.toString(16)})")
        machine.assertMemory(0x2000, 0x41)
        machine.assertMemory(0x2001, 0x36)
        machine.assertMemory(0x2002, 0x00)
        machine.assertMemory(0x2003, 0x00)
    }

    test("double increment/decrement of uword struct field via typed pointer") {
        val src = $$"""
            %option no_sysinit
            %launcher none
            %address $1000

            main {
                &ubyte poweroff = $f203
                &uword result = $02

                struct Sprite {
                    ubyte pad
                    ubyte pad2
                    uword x
                }

                ^^Sprite[4] sprites

                sub start() {
                    ^^Sprite sprite = sprites[0]

                    sprite.x = 255
                    sprite.x++
                    sprite.x++
                    result = sprite.x     ; expect $0101
                    poweroff = 1
                }
            }
        """.trimIndent()

        val compileResult = compileText(Cx16Target(), false, src, outputDir)
        var machine = compileResult!!.simulate()
        machine.assertMemory(0x02, 0x01)
        machine.assertMemory(0x03, 0x01)

        val src2 = $$"""
            %option no_sysinit
            %launcher none
            %address $1000

            main {
                &ubyte poweroff = $f203
                &uword result = $02

                struct Sprite {
                    ubyte pad
                    ubyte pad2
                    uword x
                }

                ^^Sprite[4] sprites

                sub start() {
                    ^^Sprite sprite = sprites[0]

                    sprite.x = 1
                    sprite.x--
                    sprite.x--
                    result = sprite.x     ; expect $ffff
                    poweroff = 1
                }
            }
        """.trimIndent()

        val compileResult2 = compileText(Cx16Target(), false, src2, outputDir)
        machine = compileResult2!!.simulate()
        machine.assertMemory(0x02, 0xff)
        machine.assertMemory(0x03, 0xff)
    }

    test("struct with inlined array memory layout (6502)") {
        val src = $$"""
            %option no_sysinit
            %launcher none
            %address $1000
            
            main {
                &ubyte poweroff = $f203
                struct Node {
                    ubyte a
                    bool flag
                    ubyte[5] array
                    word number
                }

                sub start() {
                    ^^Node k2 = [1, false, [65,66,67,68,0], 9999]
                    ^^Node k3 = $4000
                    k3^^=k2^^
                    poweroff = 1
                }
            }
        """.trimIndent()
        val compileResult = compileText(Cx16Target(), false, src, outputDir)
        val machine = compileResult!!.simulate()
        machine.assertMemory(0x4000, 1)
        machine.assertMemory(0x4001, 0)
        machine.assertMemory(0x4002, 65)
        machine.assertMemory(0x4003, 66)
        machine.assertMemory(0x4004, 67)
        machine.assertMemory(0x4005, 68)
        machine.assertMemory(0x4006, 0)
        machine.assertMemory(0x4007, 9999 and 0xff)
        machine.assertMemory(0x4008, (9999 shr 8) and 0xff)
    }

    test("list iteration on 6502 target (sentinel comparison against &struct.field)") {
        // regression: the desugared loop's sentinel comparison `cursor == &list.Tail` used to
        // crash the 6502 code generator (PtAddressOf wrapping a dereference has no identifier)
        val src = $$"""
            %option no_sysinit
            %launcher none
            %address $1000

            main {
                struct MyNode {
                    ^^MyNode Succ
                    ^^MyNode Pred
                    ubyte value
                }
                struct MyList {
                    ^^MyNode Head
                    pointer Tail
                    ^^MyNode TailPred
                }
                &ubyte poweroff = $f203
                &ubyte count = $02
                &ubyte sum = $03

                sub start() {
                    ^^MyList mylist = memory("mylist", sizeof(MyList), 0)
                    ^^MyNode n1 = memory("n1", sizeof(MyNode), 0)
                    ^^MyNode n2 = memory("n2", sizeof(MyNode), 0)
                    ^^MyNode n3 = memory("n3", sizeof(MyNode), 0)
                    mylist.Head = &mylist.Tail as ^^MyNode
                    mylist.Tail = 0
                    mylist.TailPred = &mylist.Head as ^^MyNode
                    ; append nodes to the tail of the circular list
                    n1.value = 10
                    n1.Succ = &mylist.Tail as ^^MyNode
                    n1.Pred = mylist.TailPred
                    mylist.TailPred.Succ = n1
                    mylist.TailPred = n1
                    n2.value = 20
                    n2.Succ = &mylist.Tail as ^^MyNode
                    n2.Pred = mylist.TailPred
                    mylist.TailPred.Succ = n2
                    mylist.TailPred = n2
                    n3.value = 40
                    n3.Succ = &mylist.Tail as ^^MyNode
                    n3.Pred = mylist.TailPred
                    mylist.TailPred.Succ = n3
                    mylist.TailPred = n3
                    ; forward traversal using implicit loop var (inferred ^^MyNode)
                    for node in mylist {
                        if node==0 { break }
                        count++
                        sum += node.value
                    }
                    poweroff = 1
                }
            }
        """.trimIndent()

        val compileResult = compileText(Cx16Target(), false, src, outputDir)
        val machine = compileResult!!.simulate()
        machine.assertMemory(0x02, 3)
        machine.assertMemory(0x03, 70)
    }
