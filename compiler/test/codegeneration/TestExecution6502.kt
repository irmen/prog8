/**
 * These tests execute the compiled 6502 code in the ksim65 simulator.
 * To interface correctly with the simulator, the following directives are required in the Prog8 source:
 *
 * - %option no_sysinit: Prevents the inclusion of the standard system initialization code which is not needed here.
 * - %launcher none: No need for a program launcher.
 * - %address $1000: The program should be loaded at $1000, which is where the simulator starts execution.
 * - You can use memory-mapped variables to easily read their values after execution.
 * - Best practice is to cleanly power off the simulator by writing to the poweroff register at $f203.
 * - The Disassembler class can be used to disassemble the code loaded into the simulator's memory.
 *   That is an alternative way to see what assembly code is generated by Prog8. (the usual way is to load the 64tass-generated .asm file)
 *   A big benefit of using the Disassembler could be that the resulting assembly source code is much more compact BUT it has NO SYMBOLS WHATSOEVER.
 *
 * Simulator hardware interface registers:
 * - $f000-$f003: Programmable Timer (4 registers).
 * - $f100-$f109: Real Time Clock (10 registers).
 * - $f200: Serial input register (read a byte from it).
 * - $f201: Serial output register (write a byte to output it).
 * - $f202: Reset register (writing any value triggers a CPU reset).
 * - $f203: Power-off register (writing any value stops the simulator).
 */
class TestExecution6502 : FunSpec({
    val outputDir = Files.createTempDirectory("prog8test")

    test("simple addition") {
        val src = $$"""
            %option no_sysinit
            %launcher none
            %address $1000
            
            main {
                &ubyte poweroff = $f203
                &ubyte result = $02    ; result is stored in memory at $02
                sub start() {
                    ubyte @shared a = 10
                    ubyte @shared b = 20
                    result = a + b + 12
                    
                    poweroff = 1 ; power off the simulator
                }
            }
        """.trimIndent()

        val compileResult = compileText(Cx16Target(), false, src, outputDir)
        val machine = compileResult!!.simulate()
        machine.assertMemory(0x02, 42)
    }

    test("dynamic byte and word for loops stop before wrap") {
        val src = $$"""
            %option no_sysinit
            %launcher none
            %address $1000

            main {
                &ubyte poweroff = $f203
                &ubyte byteAscending = $02
                &ubyte byteDescending = $03
                &ubyte byteEmpty = $04
                &ubyte wordAscending = $05
                &ubyte wordDescending = $06
                &ubyte evalOrder = $07
                &ubyte orderedCount = $08
                &ubyte byteUnsignedDescending = $09
                &ubyte wordUnsignedDescending = $0a

                sub start() {
                    byte ordered
                    for ordered in getFrom() to getTo() step getStep() {
                        orderedCount++
                    }

                    byte b
                    byte @shared bfrom = 1
                    byte @shared bto = 5
                    byte @shared bstep = 2
                    for b in bfrom to bto step bstep {
                        byteAscending++
                    }

                    byte @shared bdownFrom = 5
                    byte @shared bdownTo = 1
                    byte @shared bdownStep = -2
                    for b in bdownFrom to bdownTo step bdownStep {
                        byteDescending++
                    }

                    ubyte ub
                    ubyte @shared ubFrom = 5
                    ubyte @shared ubTo = 1
                    byte @shared ubStep = -2
                    for ub in ubFrom to ubTo step ubStep {
                        byteUnsignedDescending++
                    }

                    byte @shared zeroStep = 0
                    for b in bfrom to bto step zeroStep {
                        byteEmpty++
                    }

                    uword w
                    uword @shared wfrom = 65530
                    uword @shared wto = 65535
                    uword @shared wstep = 3
                    for w in wfrom to wto step wstep {
                        wordAscending++
                    }

                    word wdown
                    word @shared wdownFrom = 300
                    word @shared wdownTo = 290
                    word @shared wdownStep = -4
                    for wdown in wdownFrom to wdownTo step wdownStep {
                        wordDescending++
                    }

                    uword uwdown
                    uword @shared uwdownFrom = 65530
                    uword @shared uwdownTo = 65520
                    word @shared uwdownStep = -3
                    for uwdown in uwdownFrom to uwdownTo step uwdownStep {
                        wordUnsignedDescending++
                    }

                    poweroff = 1
                }

                sub getFrom() -> byte {
                    evalOrder = 1
                    return 1
                }

                sub getTo() -> byte {
                    evalOrder = evalOrder * 10 + 2
                    return 5
                }

                sub getStep() -> byte {
                    evalOrder = evalOrder * 10 + 3
                    return 2
                }
            }
        """.trimIndent()

        val compileResult = compileText(Cx16Target(), false, src, outputDir)
        val machine = compileResult!!.simulate()
        machine.assertMemory(0x02, 3)
        machine.assertMemory(0x03, 3)
        machine.assertMemory(0x04, 0)
        machine.assertMemory(0x05, 2)
        machine.assertMemory(0x06, 3)
        machine.assertMemory(0x07, 123)
        machine.assertMemory(0x08, 3)
        machine.assertMemory(0x09, 3)
        machine.assertMemory(0x0a, 4)
    }

    test("signed legacy loop variables stop on overflow with unsigned dynamic steps") {
