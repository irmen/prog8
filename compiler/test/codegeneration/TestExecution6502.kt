    }

    test("dynamic legacy for loop break targets remain scoped") {
        val src = $$"""
            %option no_sysinit
            %launcher none
            %address $1000

            main {
                &ubyte outerCount = $02
                &ubyte poweroff = $f203

                sub start() {
                    byte outer
                    byte inner
                    byte @shared outerFrom = 1
                    byte @shared outerTo = 3
                    byte @shared outerStep = 1
                    byte @shared innerFrom = 1
                    byte @shared innerTo = 3
                    byte @shared innerStep = 1

                    for outer in outerFrom to outerTo step outerStep {
                        for inner in innerFrom to innerTo step innerStep {
                            break
                        }
                        outerCount++
                        break
                    }
                    poweroff = 1
                }
            }
        """.trimIndent()

        val errors = ErrorReporterForTests()
        val compileResult = compileText(Cx16Target(), false, src, outputDir, errors = errors)
        if (compileResult == null)
            throw AssertionError(errors.errors.joinToString("\n"))
        val machine = compileResult.simulate()
        machine.assertMemory(0x02, 1)
    }

    test("serial output") {
        val src = $$"""
            %encoding iso
            %option no_sysinit
            %launcher none
            %address $1000
            
            main {
                &ubyte poweroff = $f203
                sub start() {
                    serial.print("HELLO!")
                    poweroff = 1 ; power off the simulator
                }
            }
            
            serial {
                &ubyte serial_out = $f201
                
                sub print(str message) {
                    repeat {
                        cx16.r0L = @(message)
                        if_z
                            return
                        serial_out = cx16.r0L
                        message++
                    }
                }
            }
            
        """.trimIndent()

        val compileResult = compileText(Cx16Target(), false, src, outputDir)
        compileResult shouldNotBe null

        val serialIO = CapturingSerialIO()
        val machine = compileResult!!.simulate(serialAndPower = serialIO)
        serialIO.assertOutput("HELLO!")
        println(machine.cpu.snapshot())
    }

